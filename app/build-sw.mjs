// Build step: write dist/sw.js with a precache list of every built file.
// Hand-written instead of a plugin so the offline behaviour is easy to audit (DECISIONS.md #4).
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const dist = new URL('./dist/', import.meta.url).pathname
const files = []
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f)
    if (statSync(p).isDirectory()) walk(p)
    else if (f !== 'sw.js') files.push(relative(dist, p).split('\\').join('/'))
  }
}
walk(dist)
const hash = createHash('sha256')
for (const f of files.sort()) hash.update(f).update(readFileSync(join(dist, f)))
const version = hash.digest('hex').slice(0, 12)

const sw = `// Keel service worker. Generated by build-sw.mjs. Cache version ${version}.
const CACHE = 'keel-${version}'
const FILES = ${JSON.stringify(['./', ...files])}
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('keel-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()))
})
self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)) }
      return res
    }).catch(() => (req.mode === 'navigate' ? caches.match('./index.html') : Response.error())))
  )
})
`
writeFileSync(join(dist, 'sw.js'), sw)
console.log(`sw.js: ${files.length} files precached, version ${version}`)
